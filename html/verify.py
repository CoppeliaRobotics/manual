#!/usr/bin/env python3
"""Sanity checks for the Markdown manual.

Usage::

    python3 verify.py [docs/en]

Hard errors (exit code 1): broken relative links, missing images, unbalanced
code fences, leftover HTML layout tags, pages without a top-level heading.
Anchor mismatches are reported as warnings: a handful of cross-references were
already broken in the original HTML manual.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

LINK_RE = re.compile(r"(?<!\!)\[[^\]]*\]\(([^)\s]+)\)")
IMAGE_RE = re.compile(r"!\[[^\]]*\]\(([^)]+)\)")
ANCHOR_ID_RE = re.compile(r'id="([^"]+)"')
FENCE_RE = re.compile(r"^(`{3,})", re.MULTILINE)
LEFTOVER_TAGS = ("<td>", "<tr>", "<table", "<tbody>", "<li>", "<div>",
                 "<span", "<font", "<br>")


def split_target(target: str) -> tuple[str, str]:
    path, _, frag = target.partition("#")
    return path, frag


def check(root: Path) -> int:
    pages = sorted(root.glob("*.md"))
    if not pages:
        print(f"no Markdown pages in {root}")
        return 1

    errors: dict[str, list[str]] = defaultdict(list)
    warnings: dict[str, list[str]] = defaultdict(list)

    ids = {p.name: set(ANCHOR_ID_RE.findall(p.read_text(encoding="utf-8"))) for p in pages}

    for page in pages:
        text = page.read_text(encoding="utf-8")
        fences = len(FENCE_RE.findall(text))
        if fences % 2:
            errors[page.name].append(f"unbalanced code fences ({fences})")
        if not any(line.startswith("# ") for line in text.splitlines()):
            errors[page.name].append("no top-level heading")

        for target in LINK_RE.findall(text):
            if target.startswith(("#", "http://", "https://", "mailto:")):
                if target.startswith("#"):
                    if target[1:] and target[1:] not in ids[page.name]:
                        warnings[page.name].append(f"missing local anchor {target}")
                continue
            path, frag = split_target(target)
            if path.endswith(".htm"):  # intentionally kept, pointing at the HTML manual
                continue
            resolved = (page.parent / path).resolve()
            if not resolved.exists():
                errors[page.name].append(f"broken link {target}")
            elif frag and resolved.suffix == ".md":
                target_ids = ids.get(resolved.name, set())
                # Fall back to the heading slug for anchors generated by the
                # Markdown renderer rather than kept as raw HTML.
                if frag not in target_ids:
                    warnings[page.name].append(f"missing anchor {target}")

        for target in IMAGE_RE.findall(text):
            if target.startswith(("http://", "https://")):
                continue
            if not (page.parent / target).exists():
                errors[page.name].append(f"missing image {target}")

        body = FENCE_RE.sub("", re.sub(r"```.*?```", "", text, flags=re.S))
        for tag in LEFTOVER_TAGS:
            if tag in body:
                errors[page.name].append(f"leftover HTML {tag}")

    hard = sum(len(v) for v in errors.values())
    soft = sum(len(v) for v in warnings.values())
    print(f"pages checked : {len(pages)}")
    print(f"hard errors   : {hard}")
    print(f"warnings      : {soft} (cross-references already broken in the original manual)")
    for name, items in list(errors.items())[:20]:
        for item in items[:5]:
            print(f"  ERROR {name}: {item}")
    return 1 if hard else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("directory", nargs="?", default=str(Path(__file__).parent / "docs" / "en"))
    args = ap.parse_args()
    return check(Path(args.directory).resolve())


if __name__ == "__main__":
    sys.exit(main())
